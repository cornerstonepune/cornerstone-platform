// The one source of the site's look (UI-14): docs/frontend/tokens.json, copied byte for byte to design-system/tokens.json,
// becomes design-system/tokens.css; the school's four logo files are copied byte for byte to public/brand/ and the
// browser tab's icon to app/icon.svg. Nothing here holds a colour: every value is read from tokens.json.
//   node apps/web/scripts/tokens.mjs           write the files
//   node apps/web/scripts/tokens.mjs --check   write nothing; exit 1 naming each file that differs from what it would write
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const web = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repo = path.resolve(web, "../..");
const LOGOS = path.join(repo, "docs/brand/cornerstone-logo/SVG-vector");
const LOGO_FILES = ["lockup-colour", "lockup-for-dark-backgrounds", "mark", "mark-on-white-tile"].map((n) => `Cornerstone-logo-${n}.svg`);

/** tokens.json → the text of tokens.css. Light values on :root, dark values under the system's dark setting. */
export function css(tokens) {
  const light = [];
  const dark = [];
  const add = (name, value) => {
    if (typeof value === "string") light.push(`  --${name}: ${value};`);
    else {
      light.push(`  --${name}: ${value.light};`);
      dark.push(`    --${name}: ${value.dark};`);
    }
  };
  for (const t of tokens.color.tokens) add(t.name, t.value);
  light.push("");
  for (const [k, v] of Object.entries(tokens.type.families)) add(`font-${k}`, v);
  for (const g of tokens.type.groups)
    for (const s of g.styles) {
      add(`font-${s.name}`, `var(--font-${g.family})`);
      add(`text-${s.name}`, s.fontSize);
      add(`lh-${s.name}`, s.lineHeight);
      add(`weight-${s.name}`, String(s.fontWeight));
      if (s.letterSpacing) add(`tracking-${s.name}`, s.letterSpacing);
    }
  light.push("");
  for (const group of ["spacing", "radius", "shadow"]) for (const t of tokens[group].tokens) add(t.name, t.value);
  // A motion token is a list of declarations ("transform: …; transition: …"): each becomes --<name>-<property>.
  for (const t of tokens.motion.tokens)
    for (const decl of t.value.split(";").map((d) => d.trim()).filter(Boolean)) {
      const i = decl.indexOf(":");
      add(`${t.name}-${decl.slice(0, i).trim()}`, decl.slice(i + 1).trim());
    }
  return [
    "/* Generated by apps/web/scripts/tokens.mjs from design-system/tokens.json (a byte copy of docs/frontend/tokens.json).",
    "   Do not edit: change docs/frontend/tokens.json and run `node apps/web/scripts/tokens.mjs`. */",
    ":root {",
    "  color-scheme: light;",
    ...light,
    "}",
    "",
    "/* Dark follows the system setting; there is no in-app switch. A page held light (data-scheme=\"light\", the whole site",
    "   until its screens are restyled) keeps the light values; tests take the dark ones by dropping the hold. */",
    "@media (prefers-color-scheme: dark) {",
    "  :root:not([data-scheme=\"light\"]) {",
    "    color-scheme: dark;",
    ...dark,
    "  }",
    "}",
    "",
  ].join("\n");
}

/** Every file this script owns: target path → the bytes it should hold. */
export function outputs() {
  const json = readFileSync(path.join(repo, "docs/frontend/tokens.json"));
  const out = new Map([
    [path.join(web, "design-system/tokens.json"), json],
    [path.join(web, "design-system/tokens.css"), Buffer.from(css(JSON.parse(json.toString("utf8"))))],
  ]);
  for (const f of LOGO_FILES) out.set(path.join(web, "public/brand", f), readFileSync(path.join(LOGOS, f)));
  out.set(path.join(web, "app/icon.svg"), readFileSync(path.join(LOGOS, "Cornerstone-logo-mark-on-white-tile.svg")));
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [file, bytes] of outputs()) {
    const same = existsSync(file) && readFileSync(file).equals(bytes);
    if (same) continue;
    if (check) {
      stale++;
      console.error(`stale: ${path.relative(repo, file)} (run node apps/web/scripts/tokens.mjs)`);
    } else writeFileSync(file, bytes);
  }
  process.exit(stale ? 1 : 0);
}
